#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { tmpdir } from "node:os";
import { prereleaseEnterRequired } from "./prerelease-state.mjs";

const root = resolve(import.meta.dirname, "..");
const outputArg = process.argv.indexOf("--output");
if (outputArg < 0 || !process.argv[outputArg + 1]) throw new Error("usage: generate-prerelease-manifest.mjs --output <path> [--image-digest sha256:...]");
const outputPath = resolve(root, process.argv[outputArg + 1]);
const imageArg = process.argv.indexOf("--image-digest");
const imageDigest = imageArg < 0 ? process.env.PROPOSED_IMAGE_DIGEST : process.argv[imageArg + 1];
if (!/^sha256:[0-9a-f]{64}$/.test(imageDigest ?? "")) throw new Error("a lowercase sha256 proposed image digest is required");

const run = (cmd, args, cwd = root, env = process.env) => execFileSync(cmd, args, { cwd, env, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
const sha256 = (path) => `sha256:${createHash("sha256").update(readFileSync(path)).digest("hex")}`;
const contract = JSON.parse(readFileSync(join(root, "release/prerelease-contract.json"), "utf8"));
const commit = run("git", ["rev-parse", "HEAD"]).trim();
if (run("git", ["status", "--porcelain", "--untracked-files=no"]).trim()) throw new Error("tracked tree must be clean before manifest generation");
const packageDirs = new Map();
for (const entry of JSON.parse(run("pnpm", ["-r", "list", "--depth", "-1", "--json"]))) {
  const manifest = JSON.parse(readFileSync(join(entry.path, "package.json"), "utf8"));
  packageDirs.set(manifest.name, { relativeDir: entry.path.slice(root.length + 1), manifest });
}

// Build from the exact committed archive and install its complete dependency
// graph. No workspace link or generated byte may resolve back to the checkout.
const stage = mkdtempSync(join(tmpdir(), "agent-wechat-prerelease-manifest-"));
let packages;
let changesets;
try {
  const archivePath = join(stage, ".source.tar");
  execFileSync("git", ["archive", "--format=tar", `--output=${archivePath}`, commit], { cwd: root });
  execFileSync("tar", ["-xf", archivePath, "-C", stage]);
  rmSync(archivePath, { force: true });
  run("pnpm", ["install", "--frozen-lockfile"], stage);

  const stageBase = realpathSync(stage);
  const stageReal = `${stageBase}${sep}`;
  const stagedWorkspaces = new Map();
  for (const entry of JSON.parse(run("pnpm", ["-r", "list", "--depth", "-1", "--json"], stage))) {
    const dir = realpathSync(entry.path);
    if (dir !== stageBase && !`${dir}${sep}`.startsWith(stageReal)) throw new Error(`workspace escapes canonical stage: ${entry.path}`);
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    stagedWorkspaces.set(manifest.name, dir);
  }
  const assertContainedLink = (path) => {
    if (!lstatSync(path).isSymbolicLink()) return;
    const real = realpathSync(path);
    if (real !== stageBase && !`${real}${sep}`.startsWith(stageReal)) throw new Error(`dependency escapes canonical stage: ${relative(stage, path)}`);
  };
  const assertContainedModules = (modules) => {
    for (const dependency of readdirSync(modules)) {
      const path = join(modules, dependency);
      assertContainedLink(path);
      if (dependency.startsWith("@") && !lstatSync(path).isSymbolicLink() && lstatSync(path).isDirectory()) {
        for (const scoped of readdirSync(path)) assertContainedLink(join(path, scoped));
      }
    }
  };
  for (const name of packageDirs.keys()) {
    const dir = stagedWorkspaces.get(name);
    if (!dir) throw new Error(`canonical stage is missing workspace ${name}`);
    const modules = join(dir, "node_modules");
    if (existsSync(modules)) assertContainedModules(modules);
  }

  changesets = readdirSync(join(stage, ".changeset"))
    .filter((name) => name.endsWith(".md") && name !== "README.md")
    .sort()
    .map((file) => ({ file: `.changeset/${file}`, sha256: sha256(join(stage, ".changeset", file)) }));

  const preState = join(stage, ".changeset", "pre.json");
  if (prereleaseEnterRequired(preState, contract.versionPrerelease)) {
    run(join(stage, "node_modules/.bin/changeset"), ["pre", "enter", contract.versionPrerelease], stage);
  }
  run(join(stage, "node_modules/.bin/changeset"), ["version"], stage);
  run("pnpm", ["--filter", "@kyan-du/agent-wechat-shared", "build"], stage);
  for (const name of contract.publicPackages) run("pnpm", ["--filter", name, "build"], stage);
  packages = [];
  for (const name of [...contract.publicPackages].sort()) {
    const relativeDir = packageDirs.get(name)?.relativeDir;
    const manifest = JSON.parse(readFileSync(join(stage, relativeDir, "package.json"), "utf8"));
    if (!manifest.version.includes(`-${contract.versionPrerelease}.`)) throw new Error(`${name} did not receive a next prerelease version`);
    if (manifest.version === packageDirs.get(name).manifest.version) throw new Error(`${name} prerelease version did not advance`);
    const pack = JSON.parse(run("npm", ["pack", "--dry-run", "--json", "--ignore-scripts"], join(stage, relativeDir)))[0];
    if (!pack?.filename || !pack.integrity) throw new Error(`incomplete npm dry-run report for ${name}`);
    packages.push({
      name,
      currentVersion: packageDirs.get(name).manifest.version,
      proposedVersion: manifest.version,
      tarball: pack.filename,
      integrity: pack.integrity,
      shasum: pack.shasum,
      size: pack.size,
      unpackedSize: pack.unpackedSize,
      fileCount: pack.files?.length ?? 0,
    });
  }
} finally {
  rmSync(stage, { recursive: true, force: true });
}
const versions = new Set(packages.map((item) => item.proposedVersion));
if (versions.size !== 1) throw new Error(`fixed public packages have divergent proposed versions: ${[...versions].join(", ")}`);
const proposedVersion = packages[0].proposedVersion;

const manifest = {
  schema: 1,
  validationOnly: true,
  approvals: { owner: false, legalRedistribution: false },
  npmDistTag: contract.npmDistTag,
  commit,
  lockfile: { path: "pnpm-lock.yaml", sha256: sha256(join(root, "pnpm-lock.yaml")) },
  changesets,
  packages,
  proposedImage: {
    repository: contract.imageRepository,
    tag: `${contract.imageRepository}:${proposedVersion}`,
    digest: `${contract.imageRepository}@${imageDigest}`,
  },
};
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`, { flag: "wx" });
console.log(outputPath);
